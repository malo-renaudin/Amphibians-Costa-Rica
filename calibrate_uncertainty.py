"""Empirical split-conformal intervals for parcel-level future observed discovery rates.
Input CSVs are generated by tune_recurrent.py and contain columns:
cell, n, test_n, actual, prediction.
The intervals do not provide confidence intervals for latent true discovery probabilities.
"""
import json
from pathlib import Path
import numpy as np
import pandas as pd

FILES = {
    "ALL": "tuned_recurrent_all_predictions.csv",
    "HUMAN_OBSERVATION": "tuned_recurrent_human_observation_predictions.csv",
}
RNG = np.random.default_rng(173)

def conformal_quantile(errors, coverage=0.90):
    errors = np.sort(np.asarray(errors))
    k = min(len(errors), int(np.ceil((len(errors) + 1) * coverage)))
    return float(errors[k - 1])

def run(directory="."):
    directory = Path(directory)
    results = {}
    for name, filename in FILES.items():
        frame = pd.read_csv(directory / filename)
        observed = frame["actual"].to_numpy()
        predicted = frame["prediction"].to_numpy()
        residual = np.abs(observed - predicted)
        coverages, widths = [], []
        for _ in range(1000):
            permutation = RNG.permutation(len(frame))
            cal = permutation[:len(frame)//2]
            test = permutation[len(frame)//2:]
            q = conformal_quantile(residual[cal])
            lo = np.maximum(0, predicted[test] - q)
            hi = np.minimum(1, predicted[test] + q)
            coverages.append(np.mean((observed[test] >= lo) & (observed[test] <= hi)))
            widths.append(np.mean(hi - lo))
        results[name] = {
            "calibration_parcels": len(frame),
            "half_width": conformal_quantile(residual),
            "mean_heldout_coverage": float(np.mean(coverages)),
            "mean_heldout_interval_width": float(np.mean(widths)),
            "nominal_coverage": 0.9,
            "calibration_period": "2022-2024",
            "method": "1000 random 50/50 parcel-level split-conformal validations",
        }
    (directory / "atlas_calibration.json").write_text(json.dumps(results, indent=2))
    return results

if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
